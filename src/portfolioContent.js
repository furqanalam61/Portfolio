export const CONTENT_KEY = 'furqan-portfolio-content-v1';

export function normalizeContent(saved) {
  try {
    return saved ? {
      ...DEFAULT_CONTENT,
      ...saved,
      skills: saved.skillsVersion >= DEFAULT_CONTENT.skillsVersion && Array.isArray(saved.skills) ? saved.skills : DEFAULT_CONTENT.skills,
      skillsVersion: DEFAULT_CONTENT.skillsVersion,
      education: Array.isArray(saved.education) ? saved.education : DEFAULT_CONTENT.education,
      links: { ...DEFAULT_CONTENT.links, ...saved.links },
      copy: { ...DEFAULT_CONTENT.copy, ...saved.copy },
    } : DEFAULT_CONTENT;
  } catch {
    return DEFAULT_CONTENT;
  }
}

export function readContent() {
  try {
    return normalizeContent(JSON.parse(localStorage.getItem(CONTENT_KEY) || 'null'));
  } catch {
    return DEFAULT_CONTENT;
  }
}

export async function readPublishedContent() {
  const response = await fetch('/content.json', { cache: 'no-cache' });
  if (!response.ok) throw new Error('Could not load published content.');
  return normalizeContent(await response.json());
}

export function writeContent(value) {
  localStorage.setItem(CONTENT_KEY, JSON.stringify(value));
}
